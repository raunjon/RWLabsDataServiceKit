// Generates Sources/RWLabsFoundation/Region+Countries.swift
//
// Usage (from the package root, on macOS 13+):
//   swift Scripts/GenerateRegions.swift > Sources/RWLabsFoundation/Region+Countries.swift
//
// Data sources:
// - Countries: Foundation's ISO 3166-1 region list
// - Names: English region names from ICU
// - Currency: ICU's default currency for the region
// - Locale: "en_<CC>" (English text, the country's number and date conventions)
// - Time zone: the only zone listed for the country in /usr/share/zoneinfo/zone.tab,
//   or `primaryZones` below for countries with several (capital or most populous)

import Foundation

let primaryZones: [String: String] = [
    "AR": "America/Argentina/Buenos_Aires", "AU": "Australia/Sydney", "BR": "America/Sao_Paulo",
    "CA": "America/Toronto", "CD": "Africa/Kinshasa", "CL": "America/Santiago", "CN": "Asia/Shanghai",
    "CY": "Asia/Nicosia", "DE": "Europe/Berlin", "EC": "America/Guayaquil", "ES": "Europe/Madrid",
    "FM": "Pacific/Pohnpei", "GL": "America/Nuuk", "ID": "Asia/Jakarta", "KI": "Pacific/Tarawa",
    "KZ": "Asia/Almaty", "MH": "Pacific/Majuro", "MN": "Asia/Ulaanbaatar", "MX": "America/Mexico_City",
    "MY": "Asia/Kuala_Lumpur", "NZ": "Pacific/Auckland", "PF": "Pacific/Tahiti", "PG": "Pacific/Port_Moresby",
    "PS": "Asia/Hebron", "PT": "Europe/Lisbon", "RU": "Europe/Moscow",
    "UA": "Europe/Kiev",   // "Europe/Kyiv" is missing from older OS releases
    "UM": "Pacific/Midway", "US": "America/New_York", "UZ": "Asia/Tashkent",
    // Not listed in zone.tab under their own code
    "AC": "Atlantic/St_Helena", "DG": "Indian/Chagos", "EA": "Africa/Ceuta", "IC": "Atlantic/Canary",
    "TA": "Atlantic/St_Helena", "XK": "Europe/Belgrade",
]

/// Property names that read better than the camel-cased English name
let nameOverrides: [String: String] = [
    "HK": "hongKong", "MO": "macao", "MM": "myanmar", "GB": "unitedKingdom", "US": "unitedStates",
    "UM": "usOutlyingIslands", "VI": "usVirginIslands", "PS": "palestine", "CI": "coteDIvoire",
]

func camelCase(_ name: String) -> String {
    let folded = name
        .folding(options: [.diacriticInsensitive, .caseInsensitive], locale: Locale(identifier: "en_US"))
        .replacingOccurrences(of: "&", with: " and ")
        .replacingOccurrences(of: "’", with: " ")
        .replacingOccurrences(of: "'", with: " ")
    let words = folded.components(separatedBy: CharacterSet.alphanumerics.inverted).filter { !$0.isEmpty }
    return words.enumerated().map { index, word in
        index == 0 ? word.lowercased() : word.prefix(1).uppercased() + word.dropFirst().lowercased()
    }.joined()
}

let zoneTab = try String(contentsOfFile: "/usr/share/zoneinfo/zone.tab", encoding: .utf8)
var zonesByCountry: [String: [String]] = [:]
for line in zoneTab.split(separator: "\n") where !line.hasPrefix("#") {
    let fields = line.split(separator: "\t")
    guard fields.count >= 3 else { continue }
    zonesByCountry[String(fields[0]), default: []].append(String(fields[2]))
}

let english = Locale(identifier: "en_US")
struct Entry { let code, property, name, currency, zone: String }
var entries: [Entry] = []
var skipped: [String] = []

for region in Locale.Region.isoRegions.map(\.identifier).sorted()
where region.count == 2 && region.allSatisfy(\.isLetter) {
    guard let name = english.localizedString(forRegionCode: region) else { skipped.append("\(region): no name"); continue }
    guard let currency = Locale(identifier: "en_\(region)").currency?.identifier, currency != "XXX" else {
        skipped.append("\(region) \(name): no currency"); continue
    }
    let zones = zonesByCountry[region] ?? []
    guard let zone = primaryZones[region] ?? (zones.count == 1 ? zones[0] : nil) else {
        skipped.append("\(region) \(name): zones \(zones)"); continue
    }
    entries.append(Entry(code: region, property: nameOverrides[region] ?? camelCase(name), name: name, currency: currency, zone: zone))
}

let duplicates = Dictionary(grouping: entries, by: \.property).filter { $0.value.count > 1 }.keys
precondition(duplicates.isEmpty, "Duplicate property names: \(duplicates)")
for line in skipped {
    FileHandle.standardError.write(Data("skipped \(line)\n".utf8))
}

print("""
//
//  Region+Countries.swift
//  RWLabsFoundation
//
//  Generated by Scripts/GenerateRegions.swift — do not edit by hand.
//  Locale is "en_<country>" (English text with the country's formats).
//  Countries spanning several time zones use the capital's or most populous one.
//

import Foundation

public extension Region {
""")
for entry in entries {
    print("    /// \(entry.name): \(entry.currency), \(entry.zone)")
    print("    static let \(entry.property) = Region(countryCode: \"\(entry.code)\", currencyCode: \"\(entry.currency)\", locale: Locale(identifier: \"en_\(entry.code)\"), timeZone: .zone(\"\(entry.zone)\"))")
}
print("""

    /// Every country preset, ordered by country code
    static let all: [Region] = [
\(entries.map { "        .\($0.property)," }.joined(separator: "\n"))
    ]
}
""")
